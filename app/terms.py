def find_banned(text: str) -> list[str]:
    """返回文本中命中的违禁词列表。"""
    if not text:
        return []
    hits = []
    for w in BANNED_WORDS:
        if w in text and w not in hits:
            hits.append(w)
    return hits


def sanitize(text: str) -> str:
    """把文本中的违禁词替换为合规表达。"""
    for w, safe in SAFE_REPLACEMENTS.items():
        text = text.replace(w, safe)
    return text
